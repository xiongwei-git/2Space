/** Shared wire types. Private and browser-protected requests never carry document keys; ordinary public mode explicitly carries publicKey. Plaintext documents never cross the API. */
export const MAX_PAGES = 6;
export const MAX_CIPHERTEXT_BYTES = 400_000;
export const RETENTION_SECONDS = [
  0, 1800, 3600, 21600, 86400, 259200, 604800, 2592000, 7776000, 15552000,
  31536000, 63072000, 94608000,
] as const;
/** Canonical unpadded base64url; IV=12 bytes; ciphertext includes GCM tag. */
export interface EncryptedPayload {
  iv: string;
  ciphertext: string;
}
export interface PageRecord {
  id: string;
  revision: number;
  payload: EncryptedPayload;
  updatedAt: string;
}
export interface SpaceView {
  id: string;
  name?: string;
  accessMode?: "private" | "public";
  publicKey?: string;
  passwordProtected?: boolean;
  /** Present only for v3 name-based browser-password encryption. */
  protection?: BrowserPasswordProtection;
  /** Encryption generation; missing in legacy responses means zero. */
  keyRevision?: number;
  viewCount?: number;
  lastViewedAt?: string | null;
  viewerIp?: string;
  readerKey?: EncryptedPayload;
  revision: number;
  pages: PageRecord[];
  createdAt: string;
  updatedAt: string;
  expiresAt: string | null;
  retentionSeconds: number;
  role: "owner" | "reader";
}
export interface CreateSpaceRequest {
  name?: string;
  accessMode?: "private" | "public";
  publicKey?: string;
  ownerToken: string;
  retentionSeconds: number;
  page: { id: string; payload: EncryptedPayload };
}
export interface SpaceAccess {
  spaceId: string;
  token: string;
  role: "owner" | "reader";
}
export interface PlainDocument {
  title: string;
  html: string;
  text: string;
  language: string;
}
export interface ApiError {
  error: { code: string; message: string };
  currentRevision?: number;
  spaceId?: string;
}
// POST /api/spaces -> 201 SpaceView; owner token is generated by client.
// GET /api/spaces/:id -> SpaceView; Authorization: Bearer <token>.
// POST /api/spaces/:id/pages {id,payload} -> 201 PageRecord.
// PUT /api/spaces/:id/pages/:pageId {expectedRevision,payload} -> PageRecord.
// DELETE /api/spaces/:id/pages/:pageId {expectedRevision} -> 204; keep >=1 page.
// PATCH /api/spaces/:id {retentionSeconds} -> SpaceView.
// POST /api/spaces/:id/shares -> 201 {token:string}; replaces previous reader token.
// DELETE /api/spaces/:id/shares -> 204; immediately invalidates reader token.
// GET /api/spaces/:id/events -> text/event-stream; authenticated fetch (not URL token).
// SSE event: change, data: {revision:number}; client refetches. Heartbeat 15s.
// DELETE /api/spaces/:id -> 204 (owner only, no undo).
// Errors {error:{code,message}}, 401 auth, 404 missing/expired, 409 version conflict,
// 422 invalid input, 413 too large, 429 rate limit. No plaintext in errors/logs.

/** Compact v2 links are additive; v1 /s/:uuid#k=...&m/r=... stays valid. */
export const SPACE_NAME_PATTERN = /^[A-Za-z0-9_-]{1,64}$/;
export const RESERVED_SPACE_NAMES = [
  "api",
  "assets",
  "s",
  "privacy",
  "share",
  "health",
  "robots",
  "favicon",
  "index",
] as const;
export interface CompactShareRecord {
  keyEnvelope: EncryptedPayload;
  ownerEnvelope: EncryptedPayload;
}
export interface CompactShareRequest extends CompactShareRecord {
  token: string;
  replace?: boolean;
}
export interface CompactShareResponse {
  share: CompactShareRecord | null;
}

/** v3 browser-password protection. The proof cannot derive the document key. */
export const PASSWORD_KDF_ITERATIONS = 600_000;
export interface BrowserPasswordProtection {
  version: 1;
  kdf: "PBKDF2-SHA256";
  iterations: 600000;
  /** Canonical base64url, exactly 16 random bytes. */
  salt: string;
}
export interface ProtectionChallenge {
  protection: BrowserPasswordProtection | null;
  keyRevision: number;
}
export interface ChangeProtectionRequest {
  expectedRevision: number;
  expectedKeyRevision: number;
  /** Null explicitly returns a public name to ordinary, unprotected access. */
  protection: BrowserPasswordProtection | null;
  /** Independent password-derived authentication value, 32 bytes, never a document key. */
  proof?: string;
  /** Only supplied when protection=null; independently generated fresh document key. */
  publicKey?: string;
  pages: { id: string; expectedRevision: number; payload: EncryptedPayload }[];
}
